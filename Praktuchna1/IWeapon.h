#pragma once
#include <string>

// =====================================================================
// IWeapon — ІНТЕРФЕЙС стратегії.
// Це і є "Стратегія": спільний інтерфейс для всіх видів зброї.
// Нову зброю можна додати, просто реалізувавши цей інтерфейс,
// не редагуючи існуючі класи персонажів (принцип Open/Closed).
// =====================================================================
class IWeapon {
public:
    virtual ~IWeapon() = default;

    // Використати зброю (алгоритм, що змінюється)
    virtual void useWeapon() const = 0;

    // Назва зброї для виводу
    virtual std::string getName() const = 0;
};
